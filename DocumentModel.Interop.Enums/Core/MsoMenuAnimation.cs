namespace DocumentModel.Interop.Core;

/// <summary>
/// Specifies animation style for Microsoft Office command bars.
/// </summary>
public enum MsoMenuAnimation
{
  /// <summary>
  /// No animation.
  /// </summary>
  None,
  /// <summary>
  /// Random animation.
  /// </summary>
  Random,
  /// <summary>
  /// Menus unfold into view.
  /// </summary>
  Unfold,
  /// <summary>
  /// Menus slide into view.
  /// </summary>
  Slide
}
