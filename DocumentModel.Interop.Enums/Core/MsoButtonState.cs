namespace DocumentModel.Interop.Core;

/// <summary>
/// Specifies the appearance of a command bar button control.
/// </summary>
public enum MsoButtonState
{
  /// <summary>
  /// Button is not pressed down.
  /// </summary>
  Up = 0,
  /// <summary>
  /// Specifies the appearance of a command bar button control.
  /// </summary>
  Down = -1,
  /// <summary>
  /// Button is pressed down.
  /// </summary>
  Mixed = 2
}
