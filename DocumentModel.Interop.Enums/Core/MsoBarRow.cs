namespace DocumentModel.Interop.Core;

/// <summary>
/// Specifies whether a command bar is in the first row or last row relative to other command bars in the same
/// docking area.
/// </summary>
public enum MsoBarRow
{
  /// <summary>
  /// First row of docking area.
  /// </summary>
  msoBarRowFirst = 0,
  /// <summary>
  /// Specifies whether a command bar is in the first row or last row relative to other command bars in the same
  /// docking area.
  /// </summary>
  msoBarRowLast = -1
}
