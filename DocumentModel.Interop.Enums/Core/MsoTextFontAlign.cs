namespace DocumentModel.Interop.Core;

/// <summary>
/// Indicates the text alignment scheme used for an object.
/// </summary>
public enum MsoTextFontAlign
{
  /// <summary>
  /// Indicates the text alignment scheme used for an object.
  /// </summary>
  msoFontAlignMixed = -2,
  /// <summary>
  /// Indicates the text alignment scheme used for an object.
  /// </summary>
  msoFontAlignAuto = 0,
  /// <summary>
  /// Specifies that the font is aligned to the top of the object. msoFontAlignCenter2 Specifies that the font is
  /// aligned to the center of the object. msoFontAlignBaseline3 Specifies that the font is aligned to the baseline
  /// of the object. msoFontAlignBottom4 Specifies that the font is aligned to the bottom of the object.
  /// </summary>
  msoFontAlignTop = 1,
  /// <summary>
  /// Indicates the text alignment scheme used for an object.
  /// </summary>
  msoFontAlignCenter = 2,
  /// <summary>
  /// Indicates the text alignment scheme used for an object.
  /// </summary>
  msoFontAlignBaseline = 3,
  /// <summary>
  /// Indicates the text alignment scheme used for an object.
  /// </summary>
  msoFontAlignBottom = 4
}
