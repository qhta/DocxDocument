namespace DocumentModel.Interop.Word;

/// <summary>
/// Specifies the horizontal alignment for an equation.
/// </summary>
public enum WdOMathHorizAlignType
{
  /// <summary>
  /// Centered.
  /// </summary>
  Center = unchecked((int)0),
  /// <summary>
  /// Left alignment.
  /// </summary>
  Left = unchecked((int)1),
  /// <summary>
  /// Right alignment.
  /// </summary>
  Right = unchecked((int)2)
}
