namespace DocumentModel.Interop.Word;

/// <summary>
/// Specifies tab alignment.
/// </summary>
public enum WdAlignmentTabAlignment
{
  /// <summary>
  /// Left-aligned tab.
  /// </summary>
  Left = unchecked((int)0),
  /// <summary>
  /// Centered tab.
  /// </summary>
  Center = unchecked((int)1),
  /// <summary>
  /// Right-aligned tab.
  /// </summary>
  Right = unchecked((int)2)
}
