namespace DocumentModel.Interop.Word;

/// <summary>
/// Specifies tab alignment.
/// </summary>
public enum WdAlignmentTabAlignment
{
  /// <summary>
  /// Left-aligned tab.
  /// </summary>
  wdLeft = unchecked((int)0),
  /// <summary>
  /// Centered tab.
  /// </summary>
  wdCenter = unchecked((int)1),
  /// <summary>
  /// Right-aligned tab.
  /// </summary>
  wdRight = unchecked((int)2)
}
