namespace DocumentModel.Interop.Word;

/// <summary>
/// Specifies the format in which to display month names.
/// </summary>
public enum WdMonthNames
{
  /// <summary>
  /// Arabic format.
  /// </summary>
  wdMonthNamesArabic = unchecked((int)0),
  /// <summary>
  /// English format.
  /// </summary>
  wdMonthNamesEnglish = unchecked((int)1),
  /// <summary>
  /// French format.
  /// </summary>
  wdMonthNamesFrench = unchecked((int)2)
}
