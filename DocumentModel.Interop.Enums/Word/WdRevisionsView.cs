  /// Specifies whether Word displays the original version of a document or a version with revisions and formatting
  /// changes applied.
  /// </summary>
  Final = unchecked((int)0),
  /// <summary>
  /// Specifies whether Word displays the original version of a document or a version with revisions and formatting
  /// changes applied.
  /// </summary>
  Original = unchecked((int)1)
}
