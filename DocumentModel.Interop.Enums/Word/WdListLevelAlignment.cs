namespace DocumentModel.Interop.Word;

/// <summary>
/// Specifies the alignment of a list level.
/// </summary>
public enum WdListLevelAlignment
{
  /// <summary>
  /// Left aligned.
  /// </summary>
  wdListLevelAlignLeft = unchecked((int)0),
  /// <summary>
  /// Center aligned.
  /// </summary>
  wdListLevelAlignCenter = unchecked((int)1),
  /// <summary>
  /// Right aligned.
  /// </summary>
  wdListLevelAlignRight = unchecked((int)2)
}
