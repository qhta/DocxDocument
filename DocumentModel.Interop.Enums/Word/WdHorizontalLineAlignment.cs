namespace DocumentModel.Interop.Word;

/// <summary>
/// Specifies the alignment of a horizontal line.
/// </summary>
public enum WdHorizontalLineAlignment
{
  /// <summary>
  /// Aligned to the left.
  /// </summary>
  Left = unchecked((int)0),
  /// <summary>
  /// Centered.
  /// </summary>
  Center = unchecked((int)1),
  /// <summary>
  /// Aligned to the right.
  /// </summary>
  Right = unchecked((int)2)
}
