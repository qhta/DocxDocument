namespace DocumentModel.Interop.Word;

/// <summary>
/// Specifies the type of separator to place between items.
/// </summary>
public enum WdSeparatorType
{
  /// <summary>
  /// A hyphen.
  /// </summary>
  Hyphen = 0,
  /// <summary>
  /// A period.
  /// </summary>
  Period = 1,
  /// <summary>
  /// A colon.
  /// </summary>
  Colon = 2,
  /// <summary>
  /// An emphasized dash.
  /// </summary>
  EmDash = 3,
  /// <summary>
  /// A standard dash.
  /// </summary>
  EnDash = 4
}
