  /// <summary>
  /// Specifies a line spacing format to be applied to a paragraph.
  /// </summary>
  Double = 2,
  /// <summary>
  /// Specifies a line spacing format to be applied to a paragraph.
  /// </summary>
  AtLeast = 3,
  /// <summary>
  /// Specifies a line spacing format to be applied to a paragraph.
  /// </summary>
  Exactly = 4,
  /// <summary>
  /// Specifies a line spacing format to be applied to a paragraph.
  /// </summary>
  Multiple = 5
}
