namespace DocumentModel.Interop.Word;

/// <summary>
/// Specifies the unit of time for chart axes and data series.
/// </summary>
public enum XlTimeUnit
{
  /// <summary>
  /// Days
  /// </summary>
  xlDays = unchecked((int)0),
  /// <summary>
  /// Months
  /// </summary>
  xlMonths = unchecked((int)1),
  /// <summary>
  /// Years
  /// </summary>
  xlYears = unchecked((int)2)
}
