namespace DocumentModel.Interop.Word;

/// <summary>
/// Specifies what the bubble size represents on a bubble chart.
/// </summary>
public enum XlSizeRepresents
{
  /// <summary>
  /// Area of the bubble.
  /// </summary>
  Area = unchecked((int)1),
  /// <summary>
  /// Width of the bubble.
  /// </summary>
  Width = unchecked((int)2)
}
