{
  /// <summary>
  /// Normal.
  /// </summary>
  Normal = 0,
  /// <summary>
  /// Maximized.
  /// </summary>
  Maximized = 1,
  /// <summary>
  /// Minimized.
  /// </summary>
  Minimized = 2
}
